/**
 * TEOS evaluation harness - report.js
 *
 * Renders the study. One summary table, the ranked causes, and an explicit
 * statement of what the numbers cannot support.
 */

import { round, tradeStats, runDistribution, groupBy, mean, median } from './stats.js';
import { EXIT } from './arms.js';

const pct = (v, dp = 1) => (v == null ? 'n/a' : `${round(v, dp)}%`);
const egp = (v, dp = 2) => (v == null ? 'n/a' : `${v < 0 ? '' : ''}${round(v, dp)}`);
const num = (v, dp = 2) => (v == null ? 'n/a' : String(round(v, dp)));
const int = (v) => (v == null ? 'n/a' : String(Math.round(v)));

function table(headers, rows) {
  const widths = headers.map((h, i) => Math.max(
    String(h).length,
    ...rows.map((r) => String(r[i] ?? '').length),
  ));
  const line = (cells) => cells.map((c, i) => String(c ?? '').padEnd(widths[i])).join('  ');
  return [
    line(headers),
    widths.map((w) => '-'.repeat(w)).join('  '),
    ...rows.map(line),
  ].join('\n');
}

/** Median ATR as a percent of price per instrument, averaged over seeds. */
function atrTable(study) {
  const bySym = {};
  for (const run of study.runs) {
    for (const [sym, st] of Object.entries(run.regimeStats ?? {})) {
      if (st.atrMedianPct == null) continue;
      (bySym[sym] ??= []).push(st.atrMedianPct);
    }
  }
  const out = {};
  for (const [sym, xs] of Object.entries(bySym)) out[sym] = median(xs);
  return out;
}

/**
 * The ATR multiple a given effective stop corresponds to, per instrument:
 *   multiple = (stopPct) / (atrPct of price)
 * This is the honest translation of "sweep 0.5x-4x ATR" onto a system whose
 * ATR is 4-25x smaller than its own policy stop floor.
 */
function atrEquivalents(study, stopPcts) {
  const atr = atrTable(study);
  const out = {};
  for (const s of stopPcts) {
    out[s] = Object.fromEntries(
      Object.entries(atr).map(([sym, a]) => [sym, a > 0 ? s / a : null]),
    );
  }
  return { atr, byStopPct: out };
}

