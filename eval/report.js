function perPeriodSharpeOf(run) {
  const s = run.metrics.perPeriodSharpe;
  return Number.isFinite(s) ? s : null;
}

/** fixed, flawed, fixed-minus-flawed. */
function sideBySide(fixed, flawed, dp, suffix = '') {
  const f = fixed == null ? null : Number(fixed);
  const g = flawed == null ? null : Number(flawed);
  const d = f != null && g != null ? f - g : null;
  return [num(f, dp), num(g, dp), d == null ? 'n/a' : `${round(d, dp)}${suffix}`];
}

function medianSideBySide(study, fixedKey, flawedKey, metric = 'netPnlEgp') {
  const med = (armKey) => runDistribution(
    study.runs.filter((r) => r.arm === armKey).map((r) => r.metrics[metric]),
  ).median;
  return sideBySide(med(fixedKey), med(flawedKey), 2);
}

/** Range of pooled trade counts across arms, for the like-for-like warning. */
function tradeCountSpread(study) {
  const per = study.arms.map((a) => ({
    arm: a.key,
    n: study.trades.filter((t) => t.arm === a.key).length,
  })).filter((x) => x.n > 0);
  if (per.length < 2) return null;
  const sorted = [...per].sort((a, b) => a.n - b.n);
  return {
    min: sorted[0].n, minArm: sorted[0].arm,
    max: sorted[sorted.length - 1].n, maxArm: sorted[sorted.length - 1].arm,
  };
}

/** Exit decisions of one kind emitted across a set of runs. */
function sumSignals(runs, kind) {
  return runs.reduce((s, r) => s + ((r.signalsByKind ?? {})[kind] ?? 0), 0);
}
